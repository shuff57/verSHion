//! Old figures frozen before batch 11 (track "last"): the Punnett square, the pedigree and the free-body diagram.
//! For each figure: the opening state and the plain defaults a saved figure starts from, every example and classic
//! setup, every switch and every choice alone and over each example, every number at the ends of its range and in the
//! middle, typed text in a few forms, the figure's own typed inputs (crosses and phenotype names, families and
//! overrides, forces at every direction), and a seeded mix of all the controls; each with the hash of the SVG it drew
//! at batch11-base, as a saved spec and as a share link read at link versions 1, 4 and today's. Batch 11 adds the
//! Punnett square's cell clicks, the pedigree's classic families and the free-body diagram's add buttons, none of which
//! may change how an old figure draws.
//!
//! The fixtures (tests/fixtures/last_b11_<figure>.txt) are written once by the old code
//! (`VERSHION_LAST_B11_FREEZE=1 cargo test --profile figtest --lib last_b11_frozen`) and never regenerated by the new
//! code: the check reads each saved spec and link back from the fixture, never from today's case list.
use crate::figures::{classic_setups, examples_for, registry, share, spec, start_params, FigureDef, Kind, Params, Value, SHOW_ANSWERS};

fn def(id: &str) -> FigureDef { registry().into_iter().find(|d| d.id == id).unwrap() }

pub fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

fn fixture(id: &str) -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(format!("tests/fixtures/last_b11_{}.txt", id.replace('-', "_")))
}

const TEXTS: [&str; 5] = ["", "x", "A long title for a figure that runs on", "\u{3bb} = 2 m", "A & B < C"];

struct Rng(u64);
impl Rng {
    fn next(&mut self, n: u64) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        (self.0 >> 33) % n.max(1)
    }
}

fn random_value(pd: &crate::figures::ParamDef, seen: &[Value], r: &mut Rng) -> Value {
    if !seen.is_empty() && r.next(3) == 0 {
        return seen[r.next(seen.len() as u64) as usize].clone();
    }
    match &pd.kind {
        Kind::Bool => Value::B(r.next(2) == 0),
        Kind::Choice(o) => Value::S(o[r.next(o.len() as u64) as usize].to_string()),
        Kind::Color(o) => Value::S(o[r.next(o.len() as u64) as usize].to_string()),
        Kind::Float { min, max, step } => match r.next(4) {
            0 => Value::F(*min),
            1 => Value::F(*max),
            _ => {
                let k = ((max - min) / step.max(1e-9)).floor().max(1.0) as u64;
                Value::F(min + (r.next(k + 1) as f64) * step)
            }
        },
        Kind::Int { min, max } => match r.next(3) {
            0 => Value::I(*min),
            1 => Value::I(*max),
            _ => Value::I(min + r.next((max - min).min(40) as u64 + 1) as i64),
        },
        Kind::Text => Value::S(TEXTS[r.next(TEXTS.len() as u64) as usize].to_string()),
        Kind::Long | Kind::List | Kind::Data { .. } => pd.default.clone(),
    }
}

fn sv(k: &str, v: &str) -> (String, Value) { (k.to_string(), Value::S(v.to_string())) }
fn iv(k: &str, v: i64) -> (String, Value) { (k.to_string(), Value::I(v)) }
fn fv(k: &str, v: f64) -> (String, Value) { (k.to_string(), Value::F(v)) }
fn bv(k: &str, v: bool) -> (String, Value) { (k.to_string(), Value::B(v)) }

