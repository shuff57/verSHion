//! Old pulley figures, frozen before batch 10: the opening state, every example, every switch and choice (alone and
//! over a busy figure, in each of the four setups), the sizes, strands and ramp angles at their ends, label forms, a
//! second object tied behind, mirror and colour, and a seeded mix of all the controls, each with the hash of the SVG it
//! drew at batch10-base. A saved figure stores every param and a share link only those that differ from the opening
//! state; both must still draw byte for byte what they drew (batch 10 adds a second object touching the first and the
//! contact forces between them, which change nothing until a teacher turns them on).
//!
//! The fixture is written once by the old code (`VERSHION_PULLEY_B10_FREEZE=1 cargo test --profile figtest --lib
//! pulley_b10_frozen`) and is never regenerated by the new code.
use crate::figures::{examples_for, registry, share, spec, start_params, FigureDef, Kind, Params, Value};

fn def() -> FigureDef { registry().into_iter().find(|d| d.id == "pulley").unwrap() }

fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/pulley_b10_frozen.txt") }

fn b(k: &'static str, v: bool) -> (&'static str, Value) { (k, Value::B(v)) }
fn f(k: &'static str, v: f64) -> (&'static str, Value) { (k, Value::F(v)) }
fn i(k: &'static str, v: i64) -> (&'static str, Value) { (k, Value::I(v)) }
fn s(k: &'static str, v: &str) -> (&'static str, Value) { (k, Value::S(v.to_string())) }

const SETUPS: [&str; 4] = ["Atwood", "Table", "Ramp", "Block & tackle"];
const LABS: [&str; 9] = ["m_1", "M", "", "none", "5 kg", "m_{big}", "theta", "\\vec{F}", "Mass"];
const MODES: [&str; 3] = ["Text", "Blank line", "None"];

/// Every force and the second object on, for the setup.
fn busy(setup: &str) -> Vec<(&'static str, Value)> {
    vec![
        s("setup", setup), b("tension", true), b("gravity", true), b("normal", true), s("friction", "Away from it"),
        s("accel", "Right falls"), s("surface", "Rough"), b("second", true), b("third", true),
    ]
}

/// (start from the opening state?, overrides)
fn cases() -> Vec<(bool, Vec<(&'static str, Value)>)> {
    let d = def();
    let mut out: Vec<(bool, Vec<(&'static str, Value)>)> = vec![(true, vec![]), (false, vec![])];
    for e in examples_for("pulley") {
        out.push((false, e.params.clone()));
        out.push((true, e.params));
    }
    for setup in SETUPS {
        out.push((true, vec![s("setup", setup)]));
        out.push((true, busy(setup)));
        for pd in (d.params)() {
            match &pd.kind {
                Kind::Bool => {
                    let dflt = matches!(pd.default, Value::B(true));
                    out.push((true, vec![s("setup", setup), (pd.key, Value::B(!dflt))]));
                    let mut v = busy(setup);
                    let cur = v.iter().find(|x| x.0 == pd.key).map(|x| matches!(x.1, Value::B(true))).unwrap_or(dflt);
                    v.retain(|x| x.0 != pd.key);
                    v.push((pd.key, Value::B(!cur)));
                    out.push((true, v));
                }
                Kind::Choice(opts) if pd.key != "setup" => {
                    for o in opts {
                        out.push((true, vec![s("setup", setup), (pd.key, Value::S(o.to_string()))]));
                        let mut v = busy(setup);
                        v.retain(|x| x.0 != pd.key);
                        v.push((pd.key, Value::S(o.to_string())));
                        out.push((true, v));
                    }
                }
                _ => {}
            }
        }
        // sizes at their ends and beyond, alone and busy
        for (k, vals) in [("l_size", [40, 50, 77, 200, 260]), ("r_size", [40, 50, 77, 200, 260]), ("t_size", [40, 50, 77, 200, 260])] {
            for v in vals {
                out.push((true, vec![s("setup", setup), i(k, v)]));
                let mut bz = busy(setup);
                bz.push(i(k, v));
                out.push((true, bz));
            }
        }
        for v in [1, 2, 3, 4, 5, 6] {
            out.push((true, vec![s("setup", setup), i("strands", v), b("tension", true), b("gravity", true)]));
        }
        for a in [5.0, 15.0, 22.5, 30.0, 45.0, 60.0, 75.0] {
            let mut bz = busy(setup);
            bz.push(f("angle", a));
            out.push((true, bz));
            out.push((true, vec![s("setup", setup), f("angle", a), b("gravity", true)]));
        }
        for l in LABS {
            for k in ["l_lab", "r_lab", "s_lab", "t_lab", "tens_lab", "grav_lab", "norm_lab", "fric_lab", "acc_lab", "ang_lab"] {
                let mut bz = busy(setup);
                bz.push((k, Value::S(l.into())));
                out.push((true, bz));
            }
        }
        for m in MODES {
            for k in ["l_lab_mode", "r_lab_mode", "t_lab_mode", "tens_lab_mode", "grav_lab_mode", "norm_lab_mode", "fric_lab_mode", "acc_lab_mode", "ang_lab_mode"] {
                let mut bz = busy(setup);
                bz.push((k, Value::S(m.into())));
                out.push((false, bz));
            }
        }
        for (mir, col) in [(false, true), (true, false), (true, true)] {
            let mut bz = busy(setup);
            bz.extend([b("mirror", mir), b("color", col)]);
            out.push((true, bz.clone()));
            out.push((false, bz));
        }
        for kind in ["Block", "Cart"] {
            for sz in [50, 100, 200] {
                let mut bz = busy(setup);
                bz.extend([s("l_kind", kind), i("l_size", sz), i("r_size", 250 - sz)]);
                out.push((true, bz));
                out.push((true, vec![s("setup", setup), s("l_kind", kind), i("l_size", sz), b("second", true)]));
            }
        }
    }
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_0b10_9011;
    let mut next = |n: u64| {
        seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        (seed >> 33) % n
    };
    while out.len() < 1500 {
        let mut v = vec![s("setup", SETUPS[next(4) as usize])];
        for k in ["tension", "gravity", "normal", "second", "third", "mirror", "color"] {
            if next(2) == 0 { let on = next(3) != 0; v.push(b(k, on)); }
        }
        v.push(s("friction", ["None", "Toward the pulley", "Away from it"][next(3) as usize]));
        v.push(s("accel", ["None", "Right falls", "Left falls"][next(3) as usize]));
        v.push(s("lower", ["Neither", "Left", "Right"][next(3) as usize]));
        v.push(s("third_side", ["Left", "Right"][next(2) as usize]));
        v.push(s("surface", ["Smooth", "Rough"][next(2) as usize]));
        v.push(s("l_kind", ["Block", "Cart"][next(2) as usize]));
        for k in ["l_size", "r_size", "t_size"] { v.push(i(k, 50 + next(151) as i64)); }
        v.push(i("strands", 2 + next(4) as i64));
        v.push(f("angle", 15.0 + next(46) as f64));
        for k in ["l_lab_mode", "r_lab_mode", "t_lab_mode", "tens_lab_mode", "grav_lab_mode", "norm_lab_mode", "fric_lab_mode", "acc_lab_mode", "ang_lab_mode"] {
            if next(3) == 0 { v.push((k, Value::S(MODES[next(3) as usize].into()))); }
        }
        for k in ["l_lab", "r_lab", "s_lab", "t_lab", "tens_lab", "grav_lab"] {
            if next(4) == 0 { v.push((k, Value::S(LABS[next(LABS.len() as u64) as usize].into()))); }
        }
        let base = next(3) != 0;
        out.push((base, v));
    }
    out
}

fn params(d: &FigureDef, base: bool, list: &[(&'static str, Value)]) -> Params {
    let defs = (d.params)();
    let mut p = if base { start_params(d) } else { Params::defaults(&defs) };
    for (k, v) in list { p.0.insert(k.to_string(), v.clone()); }
    p.normalize(&defs, false);
    p
}

/// Link versions an old link could carry: the first, one in the middle, the last before batch 10, now.
const LINK_VERSIONS: [u32; 3] = [1, 4, 7];

/// How many cases the fixture holds.
pub(super) const N_FROZEN: usize = 1500;

#[test]
fn pulley_b10_frozen() {
    let d = def();
    if std::env::var("VERSHION_PULLEY_B10_FREEZE").is_ok_and(|v| v == "1") {
        let mut text = String::new();
        for (base, c) in cases() {
            let p = params(&d, base, &c);
            let saved = serde_json::to_string(&spec::spec_for("pulley", &p)).unwrap();
            let link = share::encode("pulley", &p, &start_params(&d));
            let (_, changed) = share::decode(&link).unwrap();
            let mut row = format!("{}\t{saved}\t{link}", fnv(&d.svg(&p)));
            for v in LINK_VERSIONS.into_iter().chain([share::VERSION]) {
                row.push_str(&format!("\t{}", fnv(&d.svg(&share::link_params(&d, changed.clone(), v)))));
            }
            text.push_str(&row);
            text.push('\n');
        }
        std::fs::write(fixture(), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture()).expect("tests/fixtures/pulley_b10_frozen.txt");
    let mut n = 0;
    for line in text.lines().filter(|l| !l.is_empty()) {
        let cols: Vec<&str> = line.split('\t').collect();
        let (hash, saved, link) = (cols[0], cols[1], cols[2]);
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let p = spec::params_from_spec(&d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "an old saved pulley figure draws differently: {saved}");
        let (id, changed) = share::decode(link).unwrap();
        assert_eq!(id, "pulley");
        for (k, v) in LINK_VERSIONS.into_iter().chain([share::VERSION]).enumerate() {
            assert_eq!(fnv(&d.svg(&share::link_params(&d, changed.clone(), v))), cols[3 + k], "an old pulley share link (v{v}) draws differently: {link}");
        }
        n += 1;
    }
    assert_eq!(n, N_FROZEN, "the frozen pulley figures");
}
