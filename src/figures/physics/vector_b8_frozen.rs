//! Old vector diagrams, frozen before batch 8: the opening state, every example, every switch and choice (alone and
//! over a busy figure, on the plain defaults a saved figure starts from and on the bold opening state), the number of
//! vectors, the ends of the ranges, label forms and a seeded mix of all the controls, each with the hash of the SVG it
//! drew at batch8-base. A saved figure stores every param and a share link only those that differ from the opening
//! state; both must still draw byte for byte what they drew (batch 8 adds an angle mark and components per vector and
//! marks measured from the vertical, which change nothing until a teacher turns them on).
//!
//! The fixture is written once by the old code (`VERSHION_VECTOR_B8_FREEZE=1 cargo test --profile figtest --lib
//! vector_b8_frozen`) and is never regenerated by the new code.
use crate::figures::{examples_for, registry, share, spec, start_params, FigureDef, Kind, Params, Value, SHOW_ANSWERS};

fn def() -> FigureDef { registry().into_iter().find(|d| d.id == "vector-diagram").unwrap() }

fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/vector_diagram_b8_frozen.txt") }

fn b(k: &'static str, v: bool) -> (&'static str, Value) { (k, Value::B(v)) }
fn f(k: &'static str, v: f64) -> (&'static str, Value) { (k, Value::F(v)) }
fn i(k: &'static str, v: i64) -> (&'static str, Value) { (k, Value::I(v)) }
fn s(k: &'static str, v: &str) -> (&'static str, Value) { (k, Value::S(v.to_string())) }

const LABS: [&str; 10] = ["A", "F_1", "v_{net}", "", "none", "\\vec{F}", "Displacement", "\u{2212}B", "theta", "d_2"];
const MAGS: [f64; 8] = [0.0, 0.5, 1.0, 2.5, 4.0, 7.5, 11.5, 12.0];
const ANGS: [f64; 12] = [0.0, 30.0, 37.0, 45.0, 90.0, 135.0, 180.0, 200.0, 270.0, 300.0, 359.0, 360.0];
const VK: [[&str; 6]; 4] = [
    ["v1_mag", "v1_ang", "v1_lab", "v1_lab_mode", "v1_style", "v1"],
    ["v2_mag", "v2_ang", "v2_lab", "v2_lab_mode", "v2_style", "v2"],
    ["v3_mag", "v3_ang", "v3_lab", "v3_lab_mode", "v3_style", "v3"],
    ["v4_mag", "v4_ang", "v4_lab", "v4_lab_mode", "v4_style", "v4"],
];

/// (start from the opening state?, overrides)
fn cases() -> Vec<(bool, Vec<(&'static str, Value)>)> {
    let d = def();
    let mut out: Vec<(bool, Vec<(&'static str, Value)>)> = vec![(true, vec![]), (false, vec![])];
    for e in examples_for("vector-diagram") {
        out.push((false, e.params.clone()));
        out.push((true, e.params));
    }
    let busy = || vec![i("n", 3), b("mark_angle", true), b("components", true), b("axes", true), f("v3_ang", 150.0), f("v2_ang", 60.0)];
    for pd in (d.params)() {
        match &pd.kind {
            Kind::Bool => {
                for base in [false, true] {
                    let dflt = matches!(pd.default, Value::B(true));
                    out.push((base, vec![(pd.key, Value::B(!dflt))]));
                    let mut v = busy();
                    let cur = v.iter().find(|x| x.0 == pd.key).map(|x| matches!(x.1, Value::B(true))).unwrap_or(dflt);
                    v.retain(|x| x.0 != pd.key);
                    v.push((pd.key, Value::B(!cur)));
                    out.push((base, v));
                }
            }
            Kind::Choice(opts) => {
                for o in opts {
                    for base in [false, true] {
                        out.push((base, vec![(pd.key, Value::S(o.to_string()))]));
                        let mut v = busy();
                        v.retain(|x| x.0 != pd.key);
                        v.push((pd.key, Value::S(o.to_string())));
                        out.push((base, v));
                    }
                }
            }
            _ => {}
        }
    }
    // the number of vectors, with and without the resultant's marks
    for n in 0..=5 {
        for base in [false, true] {
            out.push((base, vec![i("n", n)]));
            out.push((base, vec![i("n", n), b("mark_angle", true), b("components", true), s("ang_lab_mode", "Degrees")]));
        }
    }
    // the ends of the ranges and the directions, each vector
    for k in VK {
        for m in MAGS {
            out.push((true, vec![i("n", 4), (k[0], Value::F(m)), b("mark_angle", true), b("components", true)]));
        }
        for a in ANGS {
            out.push((true, vec![i("n", 4), (k[1], Value::F(a)), b("mark_angle", true), s("ang_lab_mode", "Degrees")]));
            out.push((false, vec![i("n", 1), (k[1], Value::F(a)), (k[0], Value::F(5.0)), b("mark_angle", true), b("components", true), b("axes", true)]));
        }
        for l in LABS {
            out.push((true, vec![i("n", 4), (k[2], Value::S(l.into())), b("components", true)]));
        }
    }
    for l in LABS {
        out.push((true, vec![i("n", 2), s("res_lab", l), b("components", true), b("mark_angle", true), s("ang_lab", l)]));
        out.push((true, vec![i("n", 1), s("v1_lab", l), b("components", true), f("v1_ang", 210.0)]));
    }
    for (m, a) in [(12.0, 45.0), (12.0, 225.0), (0.5, 1.0), (12.0, 0.0), (12.0, 90.0)] {
        for base in [false, true] {
            out.push((base, vec![i("n", 4), f("v1_mag", m), f("v2_mag", m), f("v3_mag", m), f("v4_mag", m), f("v1_ang", a), f("v2_ang", a + 90.0), f("v3_ang", a), f("v4_ang", a + 90.0), b("mark_angle", true), b("components", true)]));
        }
    }
    for st in [false, true] {
        for ans in [false, true] {
            for mir in [false, true] {
                let mut v = busy();
                v.extend([b("color", st), b(SHOW_ANSWERS, ans), b("mirror", mir)]);
                out.push((true, v.clone()));
                out.push((false, v));
            }
        }
    }
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_7ec7_0b08;
    let mut next = |n: u64| {
        seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        (seed >> 33) % n
    };
    while out.len() < 600 {
        let mut v = vec![i("n", 1 + next(4) as i64)];
        for k in VK {
            v.push((k[0], Value::F(MAGS[next(MAGS.len() as u64) as usize])));
            v.push((k[1], Value::F(if next(3) == 0 { ANGS[next(ANGS.len() as u64) as usize] } else { next(360) as f64 })));
            if next(3) == 0 { v.push((k[2], Value::S(LABS[next(LABS.len() as u64) as usize].into()))); }
            v.push((k[3], Value::S(["Text", "Blank line", "None"][next(3) as usize].into())));
            v.push((k[4], Value::S(["Drawn", "Dashed", "Left off"][next(3) as usize].into())));
        }
        for k in ["resultant", "mark_angle", "components", "axes", "bold", "mirror", "color", SHOW_ANSWERS] {
            if next(2) == 0 { let on = next(3) != 0; v.push(b(k, on)); }
        }
        v.push(s("res_style", ["Drawn", "Dashed", "Left off"][next(3) as usize]));
        v.push(s("res_lab_mode", ["Text", "Blank line", "None"][next(3) as usize]));
        v.push(s("ang_lab_mode", ["Text", "Blank line", "Degrees"][next(3) as usize]));
        v.push(s("grid", ["Grid", "Axes only", "None"][next(3) as usize]));
        if next(3) == 0 { v.push(s("ang_lab", LABS[next(LABS.len() as u64) as usize])); }
        let base = next(2) == 0;
        out.push((base, v));
    }
    out
}

fn params(d: &FigureDef, base: bool, list: &[(&'static str, Value)]) -> Params {
    let defs = (d.params)();
    let mut p = if base { start_params(d) } else { Params::defaults(&defs) };
    for (k, v) in list { p.0.insert(k.to_string(), v.clone()); }
    p.normalize(&defs, false);
    p
}

/// Link versions an old link could carry: before the dashed resultant, before the bold opening state, now.
const LINK_VERSIONS: [u32; 3] = [1, 2, 6];

#[test]
fn vector_b8_frozen() {
    let d = def();
    if std::env::var("VERSHION_VECTOR_B8_FREEZE").is_ok_and(|v| v == "1") {
        let mut text = String::new();
        for (base, c) in cases() {
            let p = params(&d, base, &c);
            let saved = serde_json::to_string(&spec::spec_for("vector-diagram", &p)).unwrap();
            let link = share::encode("vector-diagram", &p, &start_params(&d));
            let (_, changed) = share::decode(&link).unwrap();
            let mut row = format!("{}\t{saved}\t{link}", fnv(&d.svg(&p)));
            for v in LINK_VERSIONS.into_iter().chain([share::VERSION]) {
                row.push_str(&format!("\t{}", fnv(&d.svg(&share::link_params(&d, changed.clone(), v)))));
            }
            text.push_str(&row);
            text.push('\n');
        }
        std::fs::write(fixture(), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture()).expect("tests/fixtures/vector_diagram_b8_frozen.txt");
    let mut n = 0;
    for line in text.lines().filter(|l| !l.is_empty()) {
        let cols: Vec<&str> = line.split('\t').collect();
        let (hash, saved, link) = (cols[0], cols[1], cols[2]);
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let p = spec::params_from_spec(&d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "an old saved figure draws differently: {saved}");
        let (id, changed) = share::decode(link).unwrap();
        assert_eq!(id, "vector-diagram");
        for (k, v) in LINK_VERSIONS.into_iter().chain([share::VERSION]).enumerate() {
            assert_eq!(fnv(&d.svg(&share::link_params(&d, changed.clone(), v))), cols[3 + k], "an old share link (v{v}) draws differently: {link}");
        }
        n += 1;
    }
    assert_eq!(n, 600, "the frozen vector diagrams");
}
