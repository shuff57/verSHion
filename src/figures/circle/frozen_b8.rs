//! Old circles, frozen before batch 8: the opening state, every example, every switch and choice (alone and over a busy figure),
//! every list in the forms it reads, and a seeded mix of all the controls, each with the hash of the SVG it drew at 5b0d647. A
//! saved figure stores every param and a share link only those that differ from the opening state; both must still draw byte for
//! byte what they drew (batch 8 adds dragging any point off the circle and moving a line's label across its line, which change
//! nothing until a teacher does them).
//!
//! The fixture is written once by the old code (`VERSHION_CIRCLE_B8_FREEZE=1 cargo test --profile figtest --lib circle_b8_frozen`)
//! and is never regenerated by the new code.
use super::tests_b5::{b, def, f, s, with};
use super::*;

fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() { h ^= *b as u64; h = h.wrapping_mul(0x100000001b3); }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/circle_b8_frozen.txt") }

/// Rows a teacher could have typed in each list before batch 8 (good, odd and wrong).
const MORE: [&str; 12] = ["", "D 270", "D 270, E 150", "D 270; 45; X 10; 300", "D270, P 1 30, E, -90", "D 300 1.8r", "P 30 2r", "Q 200 0.5r", "D 120 1.5 r", "d 90", "AB 45", "D 300, E 60 2.5r, F 180"];
const JOINS: [&str; 8] = ["", "AD", "AD, OD", "AD, BD, DM", "A to D", "OA", "BC, CD", "AX"];
const TANGENTS: [&str; 7] = ["", "B", "B, C", "D", "P", "P T U", "P T -"];
const MARKS: [&str; 10] = ["", "AB length", "OA x", "arc AB degrees", "arc AB length", "major arc AB 200\u{b0}", "angle OAB", "angle OAB 40\u{b0}", "BD length, angle ADB", "tangent A t"];
const STYLES: [&str; 9] = ["", "OA ticks 2", "OA arrows 1", "OA dashed", "OA dotted", "OA past A arrow", "AB past both dot", "arc AB ticks 1", "angle OAB arcs 2"];
const SHADES: [&str; 6] = ["", "segment AB", "sector AB", "major segment AB", "at 0.1 0.1", "segment AD"];

fn cases() -> Vec<Vec<(&'static str, Value)>> {
    let mut out: Vec<Vec<(&'static str, Value)>> = vec![vec![]];
    for e in examples("circle").unwrap() { out.push(e.params); }
    let busy = || vec![b("show_b", true), b("show_c", true), b("show_chord", true), b("show_bisector", true), b("show_tangent", true), b("show_secant", true), b("show_central", true), b("show_inscribed", true), s("arc", "Minor"), s("sector", "Minor"), b("m_arc", true), b("m_sector", true), b("m_chord", true), b("m_om", true), b("m_inscribed", true)];
    for pd in (def().params)() {
        match &pd.kind {
            Kind::Bool => {
                let dflt = matches!(pd.default, Value::B(true));
                out.push(vec![(pd.key, Value::B(!dflt))]);
                let mut v = busy();
                let cur = busy().iter().find(|x| x.0 == pd.key).map(|x| matches!(x.1, Value::B(true))).unwrap_or(dflt);
                v.retain(|x| x.0 != pd.key);
                v.push((pd.key, Value::B(!cur)));
                out.push(v);
            }
            Kind::Choice(opts) => for o in opts {
                out.push(vec![(pd.key, Value::S(o.to_string()))]);
                let mut v = busy();
                v.retain(|x| x.0 != pd.key);
                v.push((pd.key, Value::S(o.to_string())));
                out.push(v);
            },
            _ => {}
        }
    }
    // every list form, on a figure with B, C and a chord
    let base = || vec![b("show_b", true), b("show_c", true), b("show_chord", true)];
    for (key, rows) in [("more_points", &MORE[..]), ("joins", &JOINS[..]), ("tangents", &TANGENTS[..]), ("marks", &MARKS[..]), ("styles", &STYLES[..]), ("shade", &SHADES[..])] {
        for r in rows {
            let mut v = base();
            v.push(s("more_points", "D 300, P 30 2r"));
            v.push((key, Value::S(r.to_string())));
            out.push(v);
        }
    }
    for r in ["N AB", "N BD", "N AC, K OA"] { out.push(vec![b("show_b", true), s("more_points", "D 300"), s("midpoints", r)]); }
    for r in ["E AC BD", "E PQ circle", "E AD circle 2", "E AX BD"] { out.push(vec![b("show_b", true), b("show_c", true), s("more_points", "D 300, P 30 2r, Q 200 0.5r"), s("joins", "AC, BD, PQ, AD"), s("crossings", r)]); }
    // the ends of the ranges, the sizes and the copies
    for (r, dec) in [(0.1, 0), (10000.0, 4), (5.0, 2), (7.25, 1)] {
        for ls in ["Small", "Medium", "Large"] {
            out.push(vec![f("radius", r), (("dec"), Value::I(dec)), s("label_size", ls), b("show_chord", true), b("show_b", true), b("m_chord", true)]);
        }
    }
    for st in ["Colour", "Print"] { for ans in [true, false] { let mut v = busy(); v.push(s("style", st)); v.push(b(SHOW_ANSWERS, ans)); out.push(v); } }
    for (a, bb, c) in [(0.0, 0.0, 0.0), (0.0, 180.0, 90.0), (359.0, 1.0, 180.0), (90.0, 90.5, 270.0), (20.0, 200.0, 110.0), (45.0, 135.0, 300.0)] {
        let mut v = busy();
        v.extend([f("a1", a), f("a2", bb), f("c_angle", c)]);
        out.push(v);
    }
    for def_by in ["Points", "Angle", "Chord length", "OM distance"] {
        out.push(vec![s("define", def_by), f("chord_len", 6.0), f("om_dist", 4.0), f("theta", 250.0), b("show_chord", true), s("arc", "Major"), b("m_chord", true), b("m_om", true)]);
    }
    for n in pts::POLYGONS { out.push(vec![s("polygon", n), b("show_b", true), s("more_points", "D 200")]); }
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_c1c1_e0b8;
    let mut next = |n: u64| { seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407); (seed >> 33) % n };
    while out.len() < 420 {
        let mut v = vec![f("a1", next(360) as f64), f("a2", next(360) as f64), f("c_angle", next(360) as f64)];
        for k in ["show_b", "show_c", "show_chord", "show_bisector", "show_tangent", "show_secant", "show_central", "show_inscribed", "show_diameter", "show_radius", "show_names", "show_centre"] {
            if next(2) == 0 { let on = next(2) == 0; v.push(b(k, on)); }
        }
        v.push(s("arc", ["None", "Minor", "Major"][next(3) as usize]));
        v.push(s("sector", ["None", "Minor", "Major"][next(3) as usize]));
        v.push(s("more_points", MORE[next(MORE.len() as u64) as usize]));
        v.push(s("joins", JOINS[next(JOINS.len() as u64) as usize]));
        v.push(s("tangents", TANGENTS[next(TANGENTS.len() as u64) as usize]));
        v.push(s("marks", MARKS[next(MARKS.len() as u64) as usize]));
        v.push(s("styles", STYLES[next(STYLES.len() as u64) as usize]));
        v.push(s("shade", SHADES[next(SHADES.len() as u64) as usize]));
        v.push(s("polygon", pts::POLYGONS[next(7) as usize]));
        v.push(s("r_label", ["Value", "Letter only", "None"][next(3) as usize]));
        v.push(s("label_size", ["Small", "Medium", "Large"][next(3) as usize]));
        v.push(s("style", ["Colour", "Print"][next(2) as usize]));
        v.push(b(SHOW_ANSWERS, next(2) == 0));
        v.push(f("radius", [5.0, 3.5, 12.0, 0.8][next(4) as usize]));
        for e in KINDS { if next(4) == 0 { v.push(b(e.2, true)); } }
        out.push(v);
    }
    out
}

#[test]
fn circle_b8_frozen() {
    use crate::figures::{share, spec};
    let d = def();
    if std::env::var("VERSHION_CIRCLE_B8_FREEZE").is_ok_and(|v| v == "1") {
        let mut text = String::new();
        for c in cases() {
            let p = with(&c);
            let saved = serde_json::to_string(&spec::spec_for("circle", &p)).unwrap();
            let link = share::encode("circle", &p, &start_params(&d));
            text.push_str(&format!("{}\t{saved}\t{link}\n", fnv(&d.svg(&p))));
        }
        std::fs::write(fixture(), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture()).expect("tests/fixtures/circle_b8_frozen.txt");
    let mut n = 0;
    for line in text.lines().filter(|l| !l.is_empty()) {
        let mut it = line.split('\t');
        let (hash, saved, link) = (it.next().unwrap(), it.next().unwrap(), it.next().unwrap());
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let p = spec::params_from_spec(&d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "an old saved figure draws differently: {saved}");
        let (id, changed) = share::decode(link).unwrap();
        assert_eq!(id, "circle");
        let p = share::link_params(&d, changed, share::version(link));
        assert_eq!(fnv(&d.svg(&p)), hash, "an old share link draws differently: {link}");
        n += 1;
    }
    assert_eq!(n, 420, "the frozen circles");
}
