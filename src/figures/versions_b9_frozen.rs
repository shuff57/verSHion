//! Old figures frozen before batch 9 (student versions and axis ends): box plot, waves, predator-prey, projectile
//! motion, population growth and gel electrophoresis. For each figure: the opening state and the plain defaults a
//! saved figure starts from, every example and classic setup, every switch and every choice alone and over each
//! example, every number at the ends of its range and in the middle, typed text in a few forms, and a seeded mix of
//! all the controls; each with the hash of the SVG it drew at batch9-base, as a saved spec and as a share link read
//! at link versions 1, 4, 5, 6 and today's. Batch 9 adds axis ends, blank axes, blank-line labels, a blank lane and
//! setups, which change nothing until a teacher turns them on, so every row must still draw byte for byte.
//!
//! The fixtures (tests/fixtures/versions_b9_<figure>.txt) are written once by the old code
//! (`VERSHION_VERSIONS_B9_FREEZE=1 cargo test --profile figtest --lib versions_b9_frozen`) and never regenerated by
//! the new code: the check reads each saved spec and link back from the fixture, never from today's case list.
use crate::figures::{classic_setups, examples_for, registry, share, spec, start_params, FigureDef, Kind, Params, Value, SHOW_ANSWERS};

pub const FIGS: [&str; 6] = ["box-plot", "waves", "predator-prey", "projectile-motion", "population-growth", "gel-electrophoresis"];

fn def(id: &str) -> FigureDef { registry().into_iter().find(|d| d.id == id).unwrap() }

pub fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

fn fixture(id: &str) -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(format!("tests/fixtures/versions_b9_{}.txt", id.replace('-', "_")))
}

const TEXTS: [&str; 5] = ["", "x", "Number of snowshoe hares (thousands)", "\u{3bb} = 2 m", "A & B < C"];

struct Rng(u64);
impl Rng {
    fn next(&mut self, n: u64) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        (self.0 >> 33) % n.max(1)
    }
}

/// A value for param `pd` drawn at random from its range, its ends, its default and the examples' values.
fn random_value(pd: &crate::figures::ParamDef, seen: &[Value], r: &mut Rng) -> Value {
    if !seen.is_empty() && r.next(3) == 0 {
        return seen[r.next(seen.len() as u64) as usize].clone();
    }
    match &pd.kind {
        Kind::Bool => Value::B(r.next(2) == 0),
        Kind::Choice(o) => Value::S(o[r.next(o.len() as u64) as usize].to_string()),
        Kind::Color(o) => Value::S(o[r.next(o.len() as u64) as usize].to_string()),
        Kind::Float { min, max, step } => match r.next(4) {
            0 => Value::F(*min),
            1 => Value::F(*max),
            _ => {
                // within the first hundredth of the range, snapped to the step (a usable figure, not a huge one)
                let span = ((max - min) * 0.01).max(*step);
                let k = (span / step.max(1e-9)).floor().max(1.0) as u64;
                Value::F(min.max(0.0f64.max(*min)) + (r.next(k + 1) as f64) * step)
            }
        },
        Kind::Int { min, max } => match r.next(3) {
            0 => Value::I(*min),
            1 => Value::I(*max),
            _ => Value::I(min + r.next((max - min).min(20) as u64 + 1) as i64),
        },
        Kind::Text => Value::S(TEXTS[r.next(TEXTS.len() as u64) as usize].to_string()),
        Kind::Long | Kind::List | Kind::Data { .. } => pd.default.clone(),
    }
}

/// (start from the opening state?, overrides)
fn cases(id: &str) -> Vec<(bool, Vec<(String, Value)>)> {
    let d = def(id);
    let defs = (d.params)();
    let mut bases: Vec<Vec<(String, Value)>> = vec![vec![]];
    for e in examples_for(id).into_iter().chain(classic_setups(id)) {
        bases.push(e.params.iter().map(|(k, v)| (k.to_string(), v.clone())).collect());
    }
    let mut out: Vec<(bool, Vec<(String, Value)>)> = Vec::new();
    for b in &bases {
        out.push((true, b.clone()));
        out.push((false, b.clone()));
    }
    let with = |b: &Vec<(String, Value)>, k: &str, v: Value| {
        let mut x: Vec<(String, Value)> = b.iter().filter(|(kk, _)| kk != k).cloned().collect();
        x.push((k.to_string(), v));
        x
    };
    // values the examples use, per key
    let mut seen: std::collections::BTreeMap<&str, Vec<Value>> = Default::default();
    for b in &bases {
        for (k, v) in b {
            if let Some(pd) = defs.iter().find(|p| p.key == k) { seen.entry(pd.key).or_default().push(v.clone()); }
        }
    }
    for (bi, b) in bases.iter().enumerate() {
        for pd in &defs {
            let vals: Vec<Value> = match &pd.kind {
                Kind::Bool => vec![Value::B(true), Value::B(false)],
                Kind::Choice(o) => o.iter().map(|s| Value::S(s.to_string())).collect(),
                Kind::Color(o) => if bi == 0 { o.iter().map(|s| Value::S(s.to_string())).collect() } else { vec![] },
                Kind::Float { min, max, .. } => if bi == 0 { vec![Value::F(*min), Value::F(*max), Value::F((min + max) / 2.0)] } else { vec![] },
                Kind::Int { min, max } => if bi == 0 { vec![Value::I(*min), Value::I(*max), Value::I((min + max) / 2)] } else { vec![] },
                Kind::Text => if bi == 0 { TEXTS.iter().map(|s| Value::S(s.to_string())).collect() } else { vec![] },
                Kind::Long | Kind::List | Kind::Data { .. } => if bi == 0 { seen.get(pd.key).cloned().unwrap_or_default().into_iter().chain([Value::S(String::new())]).collect() } else { vec![] },
            };
            for v in vals {
                out.push((bi % 2 == 0, with(b, pd.key, v)));
            }
        }
    }
    for b in &bases {
        for ans in [false, true] {
            out.push((true, with(b, SHOW_ANSWERS, Value::B(ans))));
        }
    }
    // a seeded mix of everything, over the examples
    let mut r = Rng(0x5eed_b9_0000 ^ id.len() as u64 ^ (id.as_bytes()[0] as u64) << 8);
    let target = out.len() + 300;
    while out.len() < target {
        let mut v = bases[r.next(bases.len() as u64) as usize].clone();
        for pd in &defs {
            if r.next(3) == 0 {
                let val = random_value(pd, seen.get(pd.key).map(|x| x.as_slice()).unwrap_or(&[]), &mut r);
                v = with(&v, pd.key, val);
            }
        }
        out.push((r.next(2) == 0, v));
    }
    out
}

fn params(d: &FigureDef, base: bool, list: &[(String, Value)]) -> Params {
    let defs = (d.params)();
    let mut p = if base { start_params(d) } else { Params::defaults(&defs) };
    for (k, v) in list { p.0.insert(k.clone(), v.clone()); }
    p.normalize(&defs, false);
    p
}

/// Link versions an old link could carry: v1, before the micropipette's and projectile's opening states (4, 5),
/// before the Venn tint (6), today's.
const LINK_VERSIONS: [u32; 4] = [1, 4, 5, 6];

fn check(id: &str) {
    let d = def(id);
    if std::env::var("VERSHION_VERSIONS_B9_FREEZE").is_ok_and(|v| v == "1") {
        let mut text = String::new();
        for (base, c) in cases(id) {
            let p = params(&d, base, &c);
            let saved = serde_json::to_string(&spec::spec_for(id, &p)).unwrap();
            let link = share::encode(id, &p, &start_params(&d));
            let (_, changed) = share::decode(&link).unwrap();
            // what the saved spec draws when it is read back (a load migration such as predator-prey's
            // migrate_saved_pair may tidy it), which is what a teacher opening it sees
            let sp: crate::model::FigureSpec = serde_json::from_str(&saved).unwrap();
            let mut row = format!("{}\t{saved}\t{link}", fnv(&d.svg(&spec::params_from_spec(&d, &sp))));
            for v in LINK_VERSIONS.into_iter().chain([7]) {
                row.push_str(&format!("\t{}", fnv(&d.svg(&share::link_params(&d, changed.clone(), v)))));
            }
            text.push_str(&row);
            text.push('\n');
        }
        std::fs::write(fixture(id), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture(id)).unwrap_or_else(|_| panic!("{}", fixture(id).display()));
    let mut n = 0;
    for line in text.lines().filter(|l| !l.is_empty()) {
        let cols: Vec<&str> = line.split('\t').collect();
        let (hash, saved, link) = (cols[0], cols[1], cols[2]);
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let p = spec::params_from_spec(&d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "{id}: an old saved figure draws differently: {saved}");
        let (lid, changed) = share::decode(link).unwrap();
        assert_eq!(lid, id);
        for (k, v) in LINK_VERSIONS.into_iter().chain([7]).enumerate() {
            assert_eq!(fnv(&d.svg(&share::link_params(&d, changed.clone(), v))), cols[3 + k], "{id}: an old share link (v{v}) draws differently: {link}");
        }
        n += 1;
    }
    assert!(n >= 300, "{id}: the frozen figures ({n})");
    eprintln!("{id}: {n} frozen figures draw as before");
}

