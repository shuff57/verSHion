//! Old heating and cooling curves, frozen before batch 8: the opening state, every example, every switch and choice (alone and
//! over a busy figure), the ends of every number, both titles' forms and a seeded mix of all the controls, each with the hash of
//! the SVG it drew before the batch. A saved figure stores every param and a share link only those that differ from the opening
//! state; both must still draw byte for byte what they drew (batch 8 adds segment lengths computed from the mass, the specific
//! heats and the enthalpies, which change nothing until a teacher picks them).
//!
//! The fixture is written once by the old code (`VERSHION_HEAT_B8_FREEZE=1 cargo test --profile figtest --lib heating_curve_b8_frozen`)
//! and is never regenerated by the new code.
use crate::figures::{registry, start_params, FigureDef, Kind, Params, Value};

const ID: &str = "heating-cooling-curve";

fn def() -> FigureDef { registry().into_iter().find(|d| d.id == ID).unwrap() }
fn with(list: &[(&'static str, Value)]) -> Params {
    let d = def();
    let mut p = start_params(&d);
    for (k, v) in list { p.0.insert(k.to_string(), v.clone()); }
    p.normalize(&(d.params)(), false);
    p
}
fn f(k: &'static str, v: f64) -> (&'static str, Value) { (k, Value::F(v)) }
fn b(k: &'static str, v: bool) -> (&'static str, Value) { (k, Value::B(v)) }
fn s(k: &'static str, v: &str) -> (&'static str, Value) { (k, Value::S(v.to_string())) }

fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() { h ^= *b as u64; h = h.wrapping_mul(0x100000001b3); }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/heating_curve_b8_frozen.txt") }

const SUBS: [&str; 7] = ["Water", "Ethanol", "Acetone", "Mercury", "Sodium chloride", "Substance X", "Custom"];
const NAMES: [&str; 5] = ["", "solid, solid + liquid, liquid, liquid + gas, gas", "ice, ice + water, water, water + steam, steam", "S, , L, , G", "a very long solid name, melting slowly, a liquid, boiling hard, a hot gas"];

fn cases() -> Vec<Vec<(&'static str, Value)>> {
    let d = def();
    let mut out: Vec<Vec<(&'static str, Value)>> = vec![vec![]];
    for e in super::curves::examples(ID).unwrap() { out.push(e.params); }
    let busy = || vec![b("letters", true), s("seg_labels", "States"), s("temp_labels", "m.p. and b.p."), b("supercool", true), s("mode", "Cooling"), f("start", 130.0), f("end", -30.0), s("title_style", "Text"), s("title", "Cooling water"), s("minor_grid", "2 per block")];
    // (run only by the old code, so every param here is an old one)
    for pd in (d.params)() {
        match &pd.kind {
            Kind::Bool => {
                let dflt = matches!(pd.default, Value::B(true));
                for v0 in [true, false] {
                    out.push(vec![(pd.key, Value::B(v0 != dflt))]);
                }
                let mut v = busy();
                v.retain(|x| x.0 != pd.key);
                v.push((pd.key, Value::B(!dflt)));
                out.push(v);
            }
            Kind::Choice(opts) => for o in opts.iter() {
                out.push(vec![(pd.key, Value::S(o.to_string()))]);
                let mut v = busy();
                v.retain(|x| x.0 != pd.key);
                v.push((pd.key, Value::S(o.to_string())));
                out.push(v.clone());
                // both segment-length modes with each choice
                let mut w = v.clone();
                w.push(s("scale", "Schematic"));
                out.push(w);
            },
            Kind::Float { min, max, .. } => {
                for x in [*min, *max] {
                    out.push(vec![(pd.key, Value::F(x))]);
                    out.push(vec![(pd.key, Value::F(x)), b("xaxis_fit", false)]);
                }
            }
            _ => {}
        }
    }
    // every substance heating and cooling across all its changes, each segment-length mode
    for sub in SUBS {
        for mode in ["Heating", "Cooling"] {
            for scale in ["Schematic", "To scale"] {
                for xa in ["Time", "Heat added"] {
                    out.push(vec![s("substance", sub), s("mode", mode), s("scale", scale), s("xaxis", xa), f("start", -200.0), f("end", 1600.0), b("letters", true)]);
                }
            }
        }
    }
    // custom points, including bp below mp and equal, and narrow and inverted ranges
    for (mp, bp) in [(0.0, 100.0), (20.0, 80.0), (80.0, 20.0), (50.0, 50.0), (-270.0, -260.0), (2999.0, 4000.0)] {
        for (a, z) in [(-20.0, 120.0), (120.0, -20.0), (30.0, 35.0), (-300.0, 5000.0)] {
            out.push(vec![s("substance", "Custom"), f("mp", mp), f("bp", bp), f("start", a), f("end", z)]);
        }
    }
    for n in NAMES { for ls in ["Small", "Medium", "Large"] { out.push(vec![s("phase_names", n), s("label_size", ls), s("plateau_labels", "Both states (Solid + liquid)")]); } }
    for t in ["", "x", "Heating 100 g of water from \u{2212}20 \u{b0}C to 120 \u{b0}C on a hot plate"] {
        out.push(vec![s("title_style", "Text"), s("title", t), s("xtitle", t), s("ylabel", t)]);
    }
    // typed segment times at their ends together
    for (a, m, l, bo, g) in [(0.5, 0.5, 0.5, 0.5, 0.5), (30.0, 30.0, 30.0, 30.0, 30.0), (0.5, 30.0, 0.5, 30.0, 0.5), (1.5, 2.5, 7.0, 22.5, 3.0)] {
        for mode in ["Heating", "Cooling"] {
            out.push(vec![f("t_solid", a), f("t_melt", m), f("t_liquid", l), f("t_boil", bo), f("t_gas", g), s("mode", mode), f("start", if mode == "Heating" { -20.0 } else { 120.0 }), f("end", if mode == "Heating" { 120.0 } else { -20.0 })]);
        }
    }
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_4ea7_00b8;
    let mut next = |n: u64| { seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407); (seed >> 33) % n };
    while out.len() < 400 {
        let mut v = vec![s("substance", SUBS[next(7) as usize]), s("mode", ["Heating", "Cooling"][next(2) as usize]), s("scale", ["Schematic", "To scale"][next(2) as usize])];
        v.push(f("start", next(400) as f64 - 150.0));
        v.push(f("end", next(1600) as f64 - 150.0));
        v.push(f("mp", next(200) as f64 - 100.0));
        v.push(f("bp", next(400) as f64 - 50.0));
        for k in ["t_solid", "t_melt", "t_liquid", "t_boil", "t_gas"] { if next(2) == 0 { v.push(f(k, (next(60) + 1) as f64 / 2.0)); } }
        for k in ["labels", "supercool", "letters", "plateau_dashes", "xaxis_fit"] { if next(3) == 0 { let on = next(2) == 0; v.push(b(k, on)); } }
        v.push(s("xaxis", ["Time", "Heat added"][next(2) as usize]));
        v.push(s("seg_labels", ["States", "Blank lines", "None"][next(3) as usize]));
        v.push(s("plateau_labels", ["Both states (Solid + liquid)", "The change (Melting)"][next(2) as usize]));
        v.push(s("temp_labels", ["Temperatures", "m.p. and b.p.", "Blank lines", "None"][next(4) as usize]));
        v.push(s("label_size", ["Small", "Medium", "Large"][next(3) as usize]));
        v.push(s("minor_grid", ["None", "2 per block", "4 per block", "5 per block"][next(4) as usize]));
        v.push(s("phase_names", NAMES[next(NAMES.len() as u64) as usize]));
        if next(3) == 0 { v.push(f("xaxis_to", (next(60) + 5) as f64)); v.push(f("yaxis_from", -(next(100) as f64))); }
        out.push(v);
    }
    out
}

#[test]
fn heating_curve_b8_frozen() {
    use crate::figures::{share, spec};
    let d = def();
    if std::env::var("VERSHION_HEAT_B8_FREEZE").is_ok_and(|v| v == "1") {
        let mut text = String::new();
        for c in cases() {
            let p = with(&c);
            let saved = serde_json::to_string(&spec::spec_for(ID, &p)).unwrap();
            let link = share::encode(ID, &p, &start_params(&d));
            text.push_str(&format!("{}\t{saved}\t{link}\n", fnv(&d.svg(&p))));
        }
        std::fs::write(fixture(), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture()).expect("tests/fixtures/heating_curve_b8_frozen.txt");
    let mut n = 0;
    let mut distinct = std::collections::HashSet::new();
    for line in text.lines().filter(|l| !l.is_empty()) {
        let mut it = line.split('\t');
        let (hash, saved, link) = (it.next().unwrap(), it.next().unwrap(), it.next().unwrap());
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let p = spec::params_from_spec(&d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "an old saved figure draws differently: {saved}");
        let (id, changed) = share::decode(link).unwrap();
        assert_eq!(id, ID);
        let p = share::link_params(&d, changed, share::version(link));
        assert_eq!(fnv(&d.svg(&p)), hash, "an old share link draws differently: {link}");
        distinct.insert(hash.to_string());
        n += 1;
    }
    assert_eq!(n, 400, "the frozen heating curves");
    assert!(distinct.len() > 250, "the frozen cases are mostly different figures: {}", distinct.len());
}
