//! Old particle diagrams and Bohr models, frozen before batch 10. For each: the opening state, every
//! example, every switch and choice (alone and over a busy figure), the ends of every number, the
//! text boxes empty, short and long, a sweep of lattices (one to four kinds, equal and unequal
//! counts, molecules, solid, alloy and gas states, before and after) or of atoms (every element,
//! charges, neutrons, typed shells) and a seeded mix of all the controls, each with the hash of the
//! SVG it drew before the batch. A saved figure stores every param and a share link only those that
//! differ from the opening state; both must still draw byte for byte what they drew, the link also
//! read as a version 1 and a version 7 link (batch 10 adds lattice rows, columns and spacing and a
//! hand-set proton count, which change nothing until a teacher sets them).
//!
//! The fixture is written once by the old code (`VERSHION_ATOMS_B10_FREEZE=1 cargo test --profile
//! figtest --lib atoms_b10_frozen`) and is never regenerated by the new code.
use crate::figures::{examples_for, registry, start_params, FigureDef, Kind, Params, Value};

pub(super) const IDS: [&str; 2] = ["particle-diagram", "bohr-model"];

fn def(id: &str) -> FigureDef { registry().into_iter().find(|d| d.id == id).unwrap() }
fn with(d: &FigureDef, list: &[(&'static str, Value)]) -> Params {
    let mut p = start_params(d);
    for (k, v) in list { p.0.insert(k.to_string(), v.clone()); }
    p.normalize(&(d.params)(), false);
    p
}
fn b(k: &'static str, v: bool) -> (&'static str, Value) { (k, Value::B(v)) }
fn s(k: &'static str, v: &str) -> (&'static str, Value) { (k, Value::S(v.to_string())) }
fn i(k: &'static str, v: i64) -> (&'static str, Value) { (k, Value::I(v)) }

pub(super) fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() { h ^= *b as u64; h = h.wrapping_mul(0x100000001b3); }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/atoms_b10_frozen.txt") }

const LONG: &str = "Label each particle in the box and write the formula of the substance it shows";

/// A figure with many controls away from their opening values.
fn busy(id: &str) -> Vec<(&'static str, Value)> {
    match id {
        "particle-diagram" => vec![s("layout", "Lattice"), s("state", "Solid"), i("a_count", 12), s("a_size", "XL"), s("a_shade", "Light gray"), s("a_charge", "\u{2212}"), s("a_name", "Cl\u{207b} ion"), i("b_count", 12), s("b_size", "M"), s("b_shade", "Dark gray"), s("b_charge", "+"), s("b_name", "Na\u{207a} ion"), s("key_show", "Box and key"), s("border", "Double"), s("note", "Sodium chloride"), s("title", "Ionic solid")],
        _ => vec![s("element", "17 Cl - Chlorine"), i("charge", -1), s("nucleus", "Protons and neutrons"), b("gained_lost", true), b("key", true), b("brackets", true), b("caption", true), b("shell_labels", true), s("placement", "Paired"), i("neutrons", 20), s("title", "Chloride ion")],
    }
}

/// The lattices, boxes and atoms the batch's controls act on, beyond their ends.
fn sweep(id: &str) -> Vec<Vec<(&'static str, Value)>> {
    let mut out = Vec::new();
    match id {
        "particle-diagram" => {
            let counts: [[i64; 4]; 14] = [[1, 0, 0, 0], [4, 4, 0, 0], [14, 2, 0, 0], [12, 12, 0, 0], [8, 7, 0, 0], [24, 0, 0, 0], [24, 24, 24, 24], [16, 8, 0, 0], [9, 3, 3, 0], [5, 5, 5, 5], [24, 6, 0, 0], [0, 0, 0, 7], [2, 0, 1, 0], [13, 11, 0, 0]];
            for c in counts {
                for (st, gaps) in [("Solid", false), ("Solid", true), ("Gas", false)] {
                    for (sa, sb) in [("XL", "M"), ("M", "M"), ("XS", "XL")] {
                        out.push(vec![s("layout", "Lattice"), s("state", st), b("gaps", gaps), i("a_count", c[0]), i("b_count", c[1]), i("c_count", c[2]), i("d_count", c[3]), s("a_size", sa), s("b_size", sb), s("b_shade", "Black")]);
                    }
                    out.push(vec![s("layout", "Lattice"), s("state", st), b("gaps", gaps), i("a_count", c[0]), i("b_count", c[1]), i("c_count", c[2]), i("d_count", c[3]), s("a_shape", "Four around"), s("b_shape", "Pair"), s("c_shape", "Bent")]);
                    out.push(vec![s("layout", "In a box"), s("state", st), b("gaps", gaps), i("a_count", c[0]), i("b_count", c[1]), i("c_count", c[2]), i("d_count", c[3])]);
                }
                out.push(vec![s("layout", "Lattice"), s("boxes", "Before and after"), i("a_count", c[0]), i("b_count", c[1]), i("a2_count", c[2]), i("b2_count", c[3]), s("key_show", "Box and key")]);
            }
        }
        _ => {
            for z in 1..=118usize {
                let el = crate::figures::chemistry::data::ELEMENT_CHOICES[z - 1];
                out.push(vec![s("element", el)]);
                out.push(vec![s("element", el), s("nucleus", "Symbol"), b("caption", true)]);
                if z % 7 == 0 { out.push(vec![s("element", el), s("nucleus", "Protons and neutrons"), i("charge", 2), b("brackets", true), b("gained_lost", true), b("key", true)]); }
            }
            for c in [-8, -3, -1, 1, 3, 8] {
                for nuc in ["Symbol", "Protons and neutrons", "Blank", "Balls"] { out.push(vec![s("element", "26 Fe - Iron"), i("charge", c), s("nucleus", nuc), b("brackets", true), b("caption", true)]); }
            }
            for n in [-1, 0, 1, 50, 146, 200] {
                for el in ["1 H - Hydrogen", "92 U - Uranium", "118 Og - Oganesson"] { out.push(vec![s("element", el), i("neutrons", n), s("nucleus", "Balls")]); out.push(vec![s("element", el), i("neutrons", n), s("nucleus", "Protons and neutrons")]); }
            }
            for sh in ["2, 3", "2 8 8 2", "0", "32, 32, 32", "2;8;18;32;32;18;8;2", "x", "1, 0, 0"] {
                out.push(vec![s("shells_custom", sh), b("brackets", true), b("gained_lost", true), b("key", true), i("charge", 2)]);
            }
        }
    }
    out
}

/// A seeded value for param `pd` (run only by the old code, so every param here is an old one).
fn pick(pd: &crate::figures::ParamDef, next: &mut dyn FnMut(u64) -> u64) -> Option<Value> {
    Some(match &pd.kind {
        Kind::Bool => Value::B(next(2) == 0),
        Kind::Choice(opts) => Value::S(opts[next(opts.len() as u64) as usize].to_string()),
        Kind::Float { min, max, .. } => {
            let hi = max.min(min + 1000.0);
            Value::F(((min + (hi - min) * next(10_001) as f64 / 10_000.0) * 100.0).round() / 100.0)
        }
        Kind::Int { min, max } => Value::I(min + next((max - min + 1) as u64) as i64),
        _ => return None,
    })
}

pub(super) fn cases(id: &str) -> Vec<Vec<(&'static str, Value)>> {
    let d = def(id);
    let mut out: Vec<Vec<(&'static str, Value)>> = vec![vec![], busy(id)];
    for e in examples_for(id) { out.push(e.params); }
    let defs = (d.params)();
    for pd in &defs {
        let over = |v: Value| { let mut w = busy(id); w.retain(|x| x.0 != pd.key); w.push((pd.key, v)); w };
        match &pd.kind {
            Kind::Bool => for v in [true, false] { out.push(vec![(pd.key, Value::B(v))]); out.push(over(Value::B(v))); },
            Kind::Choice(opts) => for o in opts.iter() { out.push(vec![(pd.key, Value::S(o.to_string()))]); out.push(over(Value::S(o.to_string()))); },
            Kind::Float { min, max, .. } => for x in [*min, *max, (min + max) / 2.0 + 0.123] { out.push(vec![(pd.key, Value::F(x))]); out.push(over(Value::F(x))); },
            Kind::Int { min, max } => for x in [*min, *max] { out.push(vec![(pd.key, Value::I(x))]); out.push(over(Value::I(x))); },
            Kind::Text => for t in ["", "x", LONG] { out.push(vec![(pd.key, Value::S(t.to_string()))]); out.push(over(Value::S(t.to_string()))); },
            _ => {}
        }
    }
    out.extend(sweep(id));
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_a705_0b10 ^ (id.len() as u64 * 7919);
    let mut next = |n: u64| { seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407); (seed >> 33) % n.max(1) };
    let target = out.len() + 60;
    while out.len() < target {
        let mut v = Vec::new();
        for pd in &defs {
            if next(3) == 0 { continue; }
            if matches!(pd.kind, Kind::Text) { if next(2) == 0 { v.push((pd.key, Value::S(["", "Ion", LONG][next(3) as usize].to_string()))); } continue; }
            if let Some(x) = pick(pd, &mut next) { v.push((pd.key, x)); }
        }
        out.push(v);
    }
    out
}

/// The hash of what a link draws when read as a link of version `v`.
fn link_hash(d: &FigureDef, link: &str, v: u32) -> String {
    use crate::figures::share;
    let (id, changed) = share::decode(link).unwrap();
    assert_eq!(id, d.id);
    fnv(&d.svg(&share::link_params(d, changed, v)))
}

#[test]
fn atoms_b10_frozen() {
    use crate::figures::{share, spec};
    if std::env::var("VERSHION_ATOMS_B10_FREEZE").is_ok_and(|v| v == "1") {
        let mut text = String::new();
        for id in IDS {
            let d = def(id);
            for c in cases(id) {
                let p = with(&d, &c);
                let saved = serde_json::to_string(&spec::spec_for(id, &p)).unwrap();
                let link = share::encode(id, &p, &start_params(&d));
                text.push_str(&format!("{}\t{saved}\t{link}\t{}\t{}\n", fnv(&d.svg(&p)), link_hash(&d, &link, 1), link_hash(&d, &link, 7)));
            }
        }
        std::fs::write(fixture(), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture()).expect("tests/fixtures/atoms_b10_frozen.txt");
    let defs: Vec<FigureDef> = IDS.iter().map(|id| def(id)).collect();
    let mut per = std::collections::BTreeMap::<String, (usize, std::collections::HashSet<String>)>::new();
    for line in text.lines().filter(|l| !l.is_empty()) {
        let cols: Vec<&str> = line.split('\t').collect();
        let (hash, saved, link, h1, h7) = (cols[0], cols[1], cols[2], cols[3], cols[4]);
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let d = defs.iter().find(|d| d.id == sp.id).unwrap();
        let p = spec::params_from_spec(d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "an old saved figure draws differently: {saved}");
        assert_eq!(link_hash(d, link, share::version(link)), hash, "an old share link draws differently: {link}");
        assert_eq!(link_hash(d, link, 1), h1, "an old share link read as version 1 draws differently: {link}");
        assert_eq!(link_hash(d, link, 7), h7, "an old share link read as version 7 draws differently: {link}");
        let e = per.entry(sp.id.clone()).or_default();
        e.0 += 1;
        e.1.insert(hash.to_string());
    }
    assert_eq!(per.len(), 2, "both figures are frozen");
    for (id, (n, distinct)) in &per {
        assert!(*n >= 100, "{id}: {n} frozen cases");
        // a third: many particle-diagram controls belong to kinds or a second box the case leaves empty
        assert!(distinct.len() * 3 > *n, "{id}: the frozen cases are mostly different figures ({} of {n})", distinct.len());
    }
}
