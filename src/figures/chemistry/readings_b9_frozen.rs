//! Old reading figures, frozen before batch 9: the temperature, volume, gas syringe, displacement,
//! micropipette, spring scale and ruler readings. For each: the opening state, every example, every
//! switch and choice (alone and over a busy figure), the ends of every number, both titles' forms
//! and a seeded mix of all the controls, each with the hash of the SVG it drew before the batch. A
//! saved figure stores every param and a share link only those that differ from the opening state;
//! both must still draw byte for byte what they drew, the link also read as a version 1 and a
//! version 6 link (batch 9 adds Random buttons, a 2-place digital probe and a 600 mL beaker, which
//! change nothing until a teacher picks them).
//!
//! The fixture is written once by the old code (`VERSHION_READINGS_B9_FREEZE=1 cargo test --profile
//! figtest --lib readings_b9_frozen`) and is never regenerated by the new code.
use crate::figures::{examples_for, registry, start_params, FigureDef, Kind, Params, Value};

pub(super) const IDS: [&str; 7] = ["temperature-reading", "volume-reading", "gas-syringe", "volume-by-displacement", "micropipette-reading", "spring-scale", "ruler-reading"];

fn def(id: &str) -> FigureDef { registry().into_iter().find(|d| d.id == id).unwrap() }
fn with(d: &FigureDef, list: &[(&'static str, Value)]) -> Params {
    let mut p = start_params(d);
    for (k, v) in list { p.0.insert(k.to_string(), v.clone()); }
    p.normalize(&(d.params)(), false);
    p
}
fn f(k: &'static str, v: f64) -> (&'static str, Value) { (k, Value::F(v)) }
fn b(k: &'static str, v: bool) -> (&'static str, Value) { (k, Value::B(v)) }
fn s(k: &'static str, v: &str) -> (&'static str, Value) { (k, Value::S(v.to_string())) }
fn i(k: &'static str, v: i64) -> (&'static str, Value) { (k, Value::I(v)) }

pub(super) fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() { h ^= *b as u64; h = h.wrapping_mul(0x100000001b3); }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/readings_b9_frozen.txt") }

