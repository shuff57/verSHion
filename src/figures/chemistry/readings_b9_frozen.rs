/// The numbers a reading figure's value runs through, beyond its ends.
fn sweep(id: &str) -> Vec<Vec<(&'static str, Value)>> {
    let mut out = Vec::new();
    match id {
        "temperature-reading" => for th in ["Liquid-in-glass", "Digital probe"] {
            for u in ["Celsius (°C)", "Kelvin (K)", "Fahrenheit (°F)"] {
                for t in [-50.0, -10.0, -4.5, 0.0, 23.45, 37.0, 110.0, 230.0, 295.4, 400.0] {
                    for pl in ["0", "0.1"] { out.push(vec![s("thermometer", th), s("unit", u), f("temperature", t), s("places", pl), b("answer", true)]); }
                }
            }
        },
        "volume-reading" => for ins in ["Graduated cylinder", "Buret", "Beaker"] {
            for sz in ["10 mL", "25 mL", "50 mL", "100 mL", "250 mL", "1000 mL"] {
                for r in [0.0, 0.05, 6.4, 23.45, 43.6, 160.0, 640.0, 1000.0] { out.push(vec![s("instrument", ins), s("size", sz), f("reading", r), b("answer", true)]); }
            }
        },
        "gas-syringe" => for sh in ["Syringe only", "With flask and stand"] {
            for sz in ["50 cm³", "100 cm³"] {
                for v in [0.0, 0.1, 23.5, 49.9, 64.0, 100.0] { out.push(vec![s("show", sh), s("size", sz), f("volume", v), b("answer", true)]); }
            }
        },
        "volume-by-displacement" => for sz in ["10 mL", "25 mL", "50 mL", "100 mL"] {
            for (a, z) in [(0.0, 0.0), (4.0, 6.0), (6.0, 4.0), (12.0, 15.5), (50.0, 63.0), (99.0, 100.0)] {
                for ob in ["Marbles", "Cube"] { out.push(vec![s("size", sz), f("before", a), f("after", z), s("object", ob), i("count", 5), b("answer", true)]); }
            }
        },
        "micropipette-reading" => for sz in ["2 µL", "10 µL", "20 µL", "100 µL", "200 µL", "1000 µL"] {
            for v in [0.0, 0.2, 1.5, 7.35, 12.5, 55.0, 137.0, 750.0, 1000.0] { out.push(vec![s("size", sz), f("volume", v), b("answer", true)]); }
        },
        "spring-scale" => for c in ["1 N", "2.5 N", "5 N", "10 N", "20 N", "30 N", "50 N"] {
            for r in [0.0, 0.37, 3.47, 9.99, 18.5, 50.0] { out.push(vec![s("cap", c), f("reading", r), b("answer", true)]); }
        },
        _ => for m in ["1 cm", "5 mm", "1 mm", "1 in", "1/2 in", "1/4 in", "1/8 in", "1/16 in", "10 cm", "5 cm"] {
            for (st, l, r) in [(0.0, 4.37, 15), (2.0, 6.45, 15), (0.0, 3.625, 6), (7.5, 17.3, 30), (0.0, 0.1, 3), (90.0, 100.0, 100)] {
                for rt in ["One estimated digit", "Nearest mark"] { out.push(vec![s("marks", m), f("start", st), f("length", l), i("ruler", r), s("read_to", rt), b("answer", true)]); }
            }
        },
    }
    out
}

/// A seeded value for param `pd` (run only by the old code, so every param here is an old one).
fn pick(pd: &crate::figures::ParamDef, next: &mut dyn FnMut(u64) -> u64) -> Option<Value> {
    Some(match &pd.kind {
        Kind::Bool => Value::B(next(2) == 0),
        Kind::Choice(opts) => Value::S(opts[next(opts.len() as u64) as usize].to_string()),
        Kind::Float { min, max, .. } => {
            let hi = max.min(min + 1000.0);
            Value::F(((min + (hi - min) * next(10_001) as f64 / 10_000.0) * 100.0).round() / 100.0)
        }
        Kind::Int { min, max } => Value::I(min + next((max - min + 1) as u64) as i64),
        _ => return None,
    })
}

pub(super) fn cases(id: &str) -> Vec<Vec<(&'static str, Value)>> {
    let d = def(id);
    let mut out: Vec<Vec<(&'static str, Value)>> = vec![vec![], busy(id)];
    for e in examples_for(id) { out.push(e.params); }
    let defs = (d.params)();
    for pd in &defs {
        let over = |v: Value| { let mut w = busy(id); w.retain(|x| x.0 != pd.key); w.push((pd.key, v)); w };
        match &pd.kind {
            Kind::Bool => for v in [true, false] { out.push(vec![(pd.key, Value::B(v))]); out.push(over(Value::B(v))); },
            Kind::Choice(opts) => for o in opts.iter() { out.push(vec![(pd.key, Value::S(o.to_string()))]); out.push(over(Value::S(o.to_string()))); },
            Kind::Float { min, max, .. } => for x in [*min, *max, (min + max) / 2.0 + 0.123] { out.push(vec![(pd.key, Value::F(x))]); out.push(over(Value::F(x))); },
            Kind::Int { min, max } => for x in [*min, *max] { out.push(vec![(pd.key, Value::I(x))]); out.push(over(Value::I(x))); },
            Kind::Text => for t in ["", "x", LONG] { out.push(vec![(pd.key, Value::S(t.to_string()))]); out.push(over(Value::S(t.to_string()))); },
            _ => {}
        }
    }
    out.extend(sweep(id));
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_4ea7_00b9 ^ (id.len() as u64 * 7919);
    let mut next = |n: u64| { seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407); (seed >> 33) % n.max(1) };
    let target = out.len() + 60;
    while out.len() < target {
        let mut v = Vec::new();
        for pd in &defs {
            if next(3) == 0 { continue; }
            if matches!(pd.kind, Kind::Text) { if next(2) == 0 { v.push((pd.key, Value::S(["", "Reading", LONG][next(3) as usize].to_string()))); } continue; }
            if let Some(x) = pick(pd, &mut next) { v.push((pd.key, x)); }
        }
        out.push(v);
    }
    out
}

/// The hash of what a link draws when read as a link of version `v`.
fn link_hash(d: &FigureDef, link: &str, v: u32) -> String {
    use crate::figures::share;
    let (id, changed) = share::decode(link).unwrap();
    assert_eq!(id, d.id);
    fnv(&d.svg(&share::link_params(d, changed, v)))
}

#[test]
fn readings_b9_frozen() {
    use crate::figures::{share, spec};
    if std::env::var("VERSHION_READINGS_B9_FREEZE").is_ok_and(|v| v == "1") {
        let mut text = String::new();
        for id in IDS {
            let d = def(id);
            for c in cases(id) {
                let p = with(&d, &c);
                let saved = serde_json::to_string(&spec::spec_for(id, &p)).unwrap();
                let link = share::encode(id, &p, &start_params(&d));
                text.push_str(&format!("{}\t{saved}\t{link}\t{}\t{}\n", fnv(&d.svg(&p)), link_hash(&d, &link, 1), link_hash(&d, &link, 6)));
            }
        }
        std::fs::write(fixture(), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture()).expect("tests/fixtures/readings_b9_frozen.txt");
    let defs: Vec<FigureDef> = IDS.iter().map(|id| def(id)).collect();
    let mut per = std::collections::BTreeMap::<String, (usize, std::collections::HashSet<String>)>::new();
    for line in text.lines().filter(|l| !l.is_empty()) {
        let cols: Vec<&str> = line.split('\t').collect();
        let (hash, saved, link, h1, h6) = (cols[0], cols[1], cols[2], cols[3], cols[4]);
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let d = defs.iter().find(|d| d.id == sp.id).unwrap();
        let p = spec::params_from_spec(d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "an old saved figure draws differently: {saved}");
        assert_eq!(link_hash(d, link, share::version(link)), hash, "an old share link draws differently: {link}");
        assert_eq!(link_hash(d, link, 1), h1, "an old share link read as version 1 draws differently: {link}");
        assert_eq!(link_hash(d, link, 6), h6, "an old share link read as version 6 draws differently: {link}");
        let e = per.entry(sp.id.clone()).or_default();
        e.0 += 1;
        e.1.insert(hash.to_string());
    }
    assert_eq!(per.len(), 7, "all seven reading figures are frozen");
    for (id, (n, distinct)) in &per {
        assert!(*n >= 100, "{id}: {n} frozen cases");
        assert!(distinct.len() * 2 > *n, "{id}: the frozen cases are mostly different figures ({} of {n})", distinct.len());
    }
}
