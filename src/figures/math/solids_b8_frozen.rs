//! Old solids, frozen before batch 8: cylinders, prisms, cones and pyramids saved or shared before measures could be typed as
//! fractions or with square roots and before the prism's height line had a switch. Per figure: the opening state, every example,
//! every switch and choice (alone and over a busy oblique figure), every number at the ends of its range, the typed boxes that
//! existed (slanted edge, slant height, label texts, unit) in good, odd and wrong forms, the older keys a saved figure may still
//! carry (hide, measure, given, show_slant), dragged labels, and a seeded mix of all the controls. Each is pinned to the hash of
//! the SVG it drew at batch8-base (9f0171d); saved specs (every param) and share links (only the changed ones) must both still
//! draw byte for byte what they drew.
//!
//! The fixture is written once by the old code (`VERSHION_SOLIDS_B8_FREEZE=1 cargo test --profile figtest --lib solids_b8_frozen`)
//! and is never regenerated by the new code.
use crate::figures::spec::{params_from_spec, spec_for};
use crate::figures::{registry, share, start_params, FigureDef, Kind, Params, Value};


pub(super) const IDS: [&str; 4] = ["cylinder", "prism", "cone", "pyramid"];
/// Cases per figure.
const PER: usize = 220;

pub(super) fn def(id: &str) -> FigureDef { registry().into_iter().find(|d| d.id == id).unwrap() }

pub(super) fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() { h ^= *b as u64; h = h.wrapping_mul(0x100000001b3); }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/solids_b8_frozen.txt") }

/// What a teacher could have typed in the slanted edge / slant height boxes (good, odd and wrong).
const TYPED: [&str; 16] = ["", "5", "13", "5/2", "3sqrt2", "3\u{221a}2", "sqrt(13)", "2pi", "0", "-3", "abc", "1/0", "1e3", " 7 ", "2.25", "1"];
const UNITS: [&str; 5] = ["cm", "", "in", "units", "metres squared"];
const TEXTS: [&str; 4] = ["x", "", "h\u{2081}", "a long label text"];

pub(super) fn with(id: &str, list: &[(&'static str, Value)]) -> Params {
    let d = def(id);
    let mut p = start_params(&d);
    for (k, v) in list { p.0.insert(k.to_string(), v.clone()); }
    p.normalize(&(d.params)(), false);
    p
}

fn s(k: &'static str, v: &str) -> (&'static str, Value) { (k, Value::S(v.to_string())) }

/// A busy oblique figure with every label on.
fn busy(id: &str) -> Vec<(&'static str, Value)> {
    let mut v = vec![s("stands", "Oblique"), ("lean", Value::F(3.0)), s("label_size", "Large")];
    for pd in (def(id).params)() {
        if pd.key.ends_with("_lab") { v.push(s(pd.key, "Measure")); }
    }
    if matches!(id, "prism" | "pyramid") { v.push(("names", Value::B(true))); }
    v
}

pub(super) fn cases(id: &str) -> Vec<Vec<(&'static str, Value)>> {
    let d = def(id);
    let defs = (d.params)();
    let mut out: Vec<Vec<(&'static str, Value)>> = vec![vec![], busy(id)];
    for e in crate::figures::math::examples(id).unwrap() { out.push(e.params); }
    for pd in &defs {
        let over = |val: Value| { let mut v = busy(id); v.retain(|x| x.0 != pd.key); v.push((pd.key, val)); v };
        match &pd.kind {
            Kind::Bool => {
                let dflt = matches!(pd.default, Value::B(true));
                out.push(vec![(pd.key, Value::B(!dflt))]);
                out.push(over(Value::B(!dflt)));
            }
            Kind::Choice(opts) => for o in opts {
                out.push(vec![(pd.key, Value::S(o.to_string()))]);
                out.push(over(Value::S(o.to_string())));
            },
            Kind::Float { min, max, .. } => for x in [*min, *max] {
                out.push(vec![(pd.key, Value::F(x))]);
                out.push(over(Value::F(x)));
            },
            Kind::Int { min, max } => for x in [*min, *max] {
                out.push(vec![(pd.key, Value::I(x))]);
                out.push(over(Value::I(x)));
            },
            _ => {}
        }
    }
    // the typed boxes that existed
    let tkey = if matches!(id, "cone" | "pyramid") { "slant" } else { "edge" };
    for t in TYPED {
        out.push(vec![s(tkey, t), s(if id == "cone" { "l_lab" } else if id == "pyramid" { "slant_lab" } else { "edge_lab" }, "Measure")]);
        let mut v = busy(id);
        v.push(s(tkey, t));
        out.push(v);
        if matches!(id, "cone" | "pyramid") { out.push(vec![s(tkey, t), s("stands", "Right"), s(if id == "cone" { "l_lab" } else { "slant_lab" }, "Measure")]); }
    }
    for u in UNITS { out.push(vec![s("unit", u)]); }
    for pd in defs.iter().filter(|pd| pd.key.ends_with("_label")) {
        for t in TEXTS {
            let lab: &'static str = Box::leak(format!("{}_lab", pd.key.trim_end_matches("_label")).into_boxed_str());
            let mut v = busy(id);
            v.retain(|x| x.0 != lab);
            v.push(s(lab, "Text"));
            v.push(s(pd.key, t));
            out.push(v);
        }
    }
    // dragged labels
    for o in ["h:12,-8", "r:-20,5;h:3,3", "length:0,30;height:-15,0;lean:4,4", "l:10,10;slant:5,-5;edge:8,0", "v0:5,5;v1:-5,-5"] {
        let mut v = busy(id);
        v.push(s("label_offsets", o));
        out.push(v);
    }
    // the sizes, the decimals and leans both ways
    for ls in ["Small", "Medium", "Large"] {
        for (lean, dec) in [(-7.5, 0), (0.0, 2), (11.25, 3)] {
            let mut v = busy(id);
            v.retain(|x| x.0 != "label_size" && x.0 != "lean");
            v.extend([s("label_size", ls), ("lean", Value::F(lean)), ("dec", Value::I(dec)), ("radius", Value::F(2.75)), ("length", Value::F(7.3)), ("height", Value::F(4.6))]);
            out.push(v);
        }
    }
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_5011_d5b8 ^ (id.len() as u64 * 7919);
    let mut next = |n: u64| { seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407); (seed >> 33) % n };
    while out.len() < PER - 8 {
        let mut v = Vec::new();
        for pd in &defs {
            if next(3) != 0 { continue; }
            match &pd.kind {
                Kind::Bool => v.push((pd.key, Value::B(next(2) == 0))),
                Kind::Choice(o) => v.push((pd.key, Value::S(o[next(o.len() as u64) as usize].to_string()))),
                Kind::Float { min, max, step } => {
                    let n = ((max - min) / step).round() as u64;
                    v.push((pd.key, Value::F(min + step * next(n + 1) as f64)));
                }
                Kind::Int { min, max } => v.push((pd.key, Value::I(min + next((max - min + 1) as u64) as i64))),
                _ if pd.key == "edge" || pd.key == "slant" => v.push(s(pd.key, TYPED[next(TYPED.len() as u64) as usize])),
                _ => {}
            }
        }
        out.push(v);
    }
    out
}

/// Older saved figures carried keys the reworked solids no longer have (migrated at load).
fn legacy(id: &str) -> Vec<Vec<(&'static str, serde_json::Value)>> {
    use serde_json::json;
    let mut out = vec![
        vec![("hide", json!("height"))],
        vec![("hide", json!("length, width, lean"))],
        vec![("hide", json!("radius slant edge apothem hypotenuse"))],
        vec![("measure", json!("Diameter"))],
        vec![("stands", json!("Oblique"))],
    ];
    if matches!(id, "cone" | "pyramid") {
        out.extend([
            vec![("given", json!("Slant height")), ("slant", json!(10.0))],
            vec![("given", json!("Height")), ("slant", json!(10.0))],
            vec![("show_slant", json!(true))],
            vec![("show_slant", json!(false))],
        ]);
    }
    while out.len() < 8 { out.push(vec![("hide", json!("side"))]); }
    out
}

#[test]
fn solids_b8_frozen() {
    let write = std::env::var("VERSHION_SOLIDS_B8_FREEZE").is_ok_and(|v| v == "1");
    if write {
        let mut text = String::new();
        for id in IDS {
            let d = def(id);
            let start = start_params(&d);
            for c in cases(id) {
                let p = with(id, &c);
                let saved = serde_json::to_string(&spec_for(id, &p)).unwrap();
                let link = share::encode(id, &p, &start);
                text.push_str(&format!("{id}\t{}\t{saved}\t{link}\n", fnv(&d.svg(&p))));
            }
            // older saved figures: today's opening state plus the legacy keys, read through the migration
            for extra in legacy(id) {
                let mut sp = spec_for(id, &start);
                for (k, v) in &extra { sp.params.insert(k.to_string(), v.clone()); }
                if extra.iter().any(|(k, _)| *k == "stands") { sp.params.remove("lean_lab"); }
                let p = params_from_spec(&d, &sp);
                let saved = serde_json::to_string(&sp).unwrap();
                text.push_str(&format!("{id}\t{}\t{saved}\t-\n", fnv(&d.svg(&p))));
            }
        }
        std::fs::write(fixture(), text).unwrap();
        return;
    }
    let text = std::fs::read_to_string(fixture()).expect("tests/fixtures/solids_b8_frozen.txt");
    let mut n = std::collections::BTreeMap::<String, usize>::new();
    for line in text.lines().filter(|l| !l.is_empty()) {
        let mut it = line.split('\t');
        let (id, hash, saved, link) = (it.next().unwrap(), it.next().unwrap(), it.next().unwrap(), it.next().unwrap());
        let d = def(id);
        let sp: crate::model::FigureSpec = serde_json::from_str(saved).unwrap();
        let p = params_from_spec(&d, &sp);
        assert_eq!(fnv(&d.svg(&p)), hash, "an old saved {id} draws differently: {saved}");
        if link != "-" {
            let (lid, changed) = share::decode(link).unwrap();
            assert_eq!(lid, id);
            let p = share::link_params(&d, changed, share::version(link));
            assert_eq!(fnv(&d.svg(&p)), hash, "an old {id} share link draws differently: {link}");
        }
        *n.entry(id.to_string()).or_default() += 1;
    }
    for id in IDS { assert!(n.get(id).copied().unwrap_or(0) >= 200, "frozen {id}s: {n:?}"); }
}

