//! Old flat shapes, frozen before batch 9: triangles, rectangles, parallelograms, trapezoids, kites and regular polygons saved or
//! shared before each height, diagonal, apothem and radius had its own line style, before the point where a height lands and
//! where the diagonals cross could be named, and before the regular polygon's size could be typed. Per figure: the opening
//! state, a busy figure (every height and diagonal drawn, every label on, Large), every example, every switch and choice alone
//! and over the busy figure, every number at the ends of its range, typed measures in good, odd and wrong forms, label texts,
//! units, dragged labels, older saved forms read through the migration, and a seeded mix of all the controls. Each is pinned to
//! the hash of the SVG it drew at batch9-base (e2c68d7); saved specs (every param) and share links (only the changed ones)
//! must both still draw byte for byte what they drew.
//!
//! The fixture is written once by the old code (`VERSHION_FLAT_B9_FREEZE=1 cargo test --profile figtest --lib flat_b9_frozen`)
//! and is never regenerated by the new code.
use crate::figures::spec::{params_from_spec, spec_for};
use crate::figures::{registry, share, start_params, FigureDef, Kind, Params, Value};

pub(super) const IDS: [&str; 6] = ["triangle", "rectangle", "parallelogram", "trapezoid", "kite", "regular-polygon"];
/// Cases per figure (before the older saved forms).
const PER: usize = 240;

pub(super) fn def(id: &str) -> FigureDef { registry().into_iter().find(|d| d.id == id).unwrap() }

pub(super) fn fnv(s: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in s.as_bytes() { h ^= *b as u64; h = h.wrapping_mul(0x100000001b3); }
    format!("{h:016x}")
}

fn fixture() -> std::path::PathBuf { std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/flat_b9_frozen.txt") }

/// What a teacher could have typed in a measure box (good, odd and wrong).
const TYPED: [&str; 14] = ["", "5", "13", "5/2", "3sqrt2", "3\u{221a}2", "sqrt(13)", "2pi", "0", "-3", "abc", "1e3", " 7 ", "2.25"];
const UNITS: [&str; 4] = ["cm", "", "in", "metres squared"];
const TEXTS: [&str; 4] = ["x", "", "h\u{2081}", "a long label text"];

pub(super) fn with(id: &str, list: &[(&'static str, Value)]) -> Params {
    let d = def(id);
    let mut p = start_params(&d);
    for (k, v) in list { p.0.insert(k.to_string(), v.clone()); }
    p.normalize(&(d.params)(), false);
    p
}

fn s(k: &'static str, v: &str) -> (&'static str, Value) { (k, Value::S(v.to_string())) }

/// A busy figure: every height and diagonal drawn, labels on, Large.
pub(super) fn busy(id: &str) -> Vec<(&'static str, Value)> {
    let mut v = vec![s("label_size", "Large")];
    match id {
        "triangle" => v.extend([s("height", "From all three"), s("m_b", "70"), s("height_label", "Measure")]),
        "rectangle" => v.extend([s("diagonals", "Drawn and labelled")]),
        "parallelogram" => v.extend([s("height", "Onto AB (from D and C)"), s("diagonals", "Drawn and labelled")]),
        "trapezoid" => v.extend([("show_height", Value::B(true)), s("hfrom", "D and C"), s("kind", "Trapezoid"), s("m_a", "60"), s("m_da", ""), s("m_h", "4"), s("diagonals", "Drawn and labelled")]),
        "kite" => v.extend([s("height", "From D and C to AB"), s("diagonals", "Drawn and labelled")]),
        _ => v.extend([("radius", Value::B(true)), ("all_radii", Value::B(true)), ("vertices", Value::B(true)), s("center_name", "O"), s("radius_label", "Measure"), s("apothem_label", "a = measure")]),
    }
    v
}

pub(super) fn cases(id: &str) -> Vec<Vec<(&'static str, Value)>> {
    let d = def(id);
    let defs = (d.params)();
    let mut out: Vec<Vec<(&'static str, Value)>> = vec![vec![], busy(id)];
    for e in crate::figures::math::examples(id).unwrap() { out.push(e.params); }
    for pd in &defs {
        let over = |val: Value| { let mut v = busy(id); v.retain(|x| x.0 != pd.key); v.push((pd.key, val)); v };
        match &pd.kind {
            Kind::Bool => {
                let dflt = matches!(pd.default, Value::B(true));
                out.push(vec![(pd.key, Value::B(!dflt))]);
                out.push(over(Value::B(!dflt)));
            }
            Kind::Choice(opts) => for o in opts {
                out.push(vec![(pd.key, Value::S(o.to_string()))]);
                out.push(over(Value::S(o.to_string())));
            },
            Kind::Float { min, max, .. } => for x in [*min, *max] {
                out.push(vec![(pd.key, Value::F(x))]);
                out.push(over(Value::F(x)));
            },
            Kind::Int { min, max } => for x in [*min, *max] {
                out.push(vec![(pd.key, Value::I(x))]);
                out.push(over(Value::I(x)));
            },
            _ => {}
        }
    }
    // typed measures in the first value box (and the trapezoid's height)
    let first = if id == "regular-polygon" { None } else { Some("m_ab") };
    if let Some(k) = first {
        for t in TYPED {
            out.push(vec![s(k, t)]);
            let mut v = busy(id);
            v.push(s(k, t));
            out.push(v);
        }
    }
    for u in UNITS { out.push(vec![s("unit", u)]); let mut v = busy(id); v.push(s("unit", u)); out.push(v); }
    for pd in defs.iter().filter(|pd| matches!(pd.kind, Kind::Text) && (pd.key.ends_with("_text") || pd.key.ends_with("_label") || pd.key.starts_with("name_") || pd.key == "center_name" || pd.key == "vnames")) {
        for t in TEXTS {
            let mut v = busy(id);
            v.push(s(pd.key, t));
            out.push(v);
        }
    }
    // dragged labels
    for o in ["h:12,-8", "ac:-20,5;bd:3,3", "s0:0,30;a0:-15,0;v1:4,4", "r:10,10;ap:5,-5;n0:8,0", "h0:5,5;h1:-5,-5"] {
        let mut v = busy(id);
        v.push(s("label_offsets", o));
        out.push(v);
    }
    // turned, flipped, sizes and decimals together
    for ls in ["Small", "Medium", "Large"] {
        for (rot, dec) in [(-135.0, 0), (0.0, 2), (47.0, 3)] {
            let mut v = busy(id);
            v.retain(|x| x.0 != "label_size");
            v.extend([s("label_size", ls), ("rotate", Value::F(rot)), ("dec", Value::I(dec)), ("flip", Value::B(rot < 0.0))]);
            out.push(v);
        }
    }
    // a seeded mix of everything
    let mut seed: u64 = 0x5eed_f1a7_b9 ^ (id.len() as u64 * 7919);
    let mut next = |n: u64| { seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407); (seed >> 33) % n };
    while out.len() < PER {
        let mut v = Vec::new();
        for pd in &defs {
            if next(3) != 0 { continue; }
            match &pd.kind {
                Kind::Bool => v.push((pd.key, Value::B(next(2) == 0))),
                Kind::Choice(o) => v.push((pd.key, Value::S(o[next(o.len() as u64) as usize].to_string()))),
                Kind::Float { min, max, step } => {
                    let n = ((max - min) / step).round() as u64;
                    v.push((pd.key, Value::F(min + step * next(n + 1) as f64)));
                }
                Kind::Int { min, max } => v.push((pd.key, Value::I(min + next((max - min + 1) as u64) as i64))),
                _ => {}
            }
        }
        out.push(v);
    }
    out
}

